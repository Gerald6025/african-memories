const ts = require('typescript');
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../lib/request-origin.ts'), 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const context = { exports: {}, URL };
vm.runInNewContext(output, context);
const check = (headers, internal = 'http://localhost:3000') => context.exports.isValidRequestOrigin(new Headers(headers), internal);
assert.equal(check({ origin: 'http://localhost:3000', host: 'localhost:3000' }), true);
assert.equal(check({ origin: 'http://192.168.1.5:3000', host: '192.168.1.5:3000' }, 'http://0.0.0.0:3000'), true);
assert.equal(check({ origin: 'https://africanmemories.com', host: 'internal:3000', 'x-forwarded-host': 'africanmemories.com', 'x-forwarded-proto': 'https' }), true);
assert.equal(check({ origin: 'https://evil.example', host: 'africanmemories.com', 'x-forwarded-proto': 'https' }), false);
assert.equal(check({ origin: 'http://localhost:3001', host: 'localhost:3000' }), false);
assert.equal(check({ origin: 'https://africanmemories.com', host: 'africanmemories.com' }), false);
assert.equal(check({ origin: 'null', host: 'localhost:3000' }), false);
assert.equal(check({ origin: 'http://localhost:3000/path', host: 'localhost:3000' }), false);
assert.equal(check({ origin: 'http://localhost:3000', host: 'localhost:3000', 'sec-fetch-site': 'cross-site' }), false);
assert.equal(check({}), true);
console.log('Request origin checks passed: local, LAN, proxy, and cross-site rejection.');
